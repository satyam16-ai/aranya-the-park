/**
 * build-manifest.mjs — src/data/{image,photo}Manifest.ts → includes/media-manifest.php
 *
 * The React <Img> looks an image up by path and gets its srcSet, intrinsic size
 * and credit ("Representational image"). WordPress needs the same facts in two
 * places: aranya_img() for images that are still plugin/theme defaults, and the
 * importer, which registers each ladder of pre-optimised WebP files as one
 * attachment so WordPress prints the very same srcset.
 *
 * Keyed by file name (the largest variant), which is also the file's name in
 * uploads/aranya/. Uses Node's built-in TypeScript type stripping (Node 22.6+).
 */
import { writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const out = join(here, '..', 'plugin', 'aranya-core', 'includes', 'media-manifest.php');

const { imageManifest } = await import(pathToFileURL(join(repo, 'src/data/imageManifest.ts')).href);
const { photoManifest } = await import(pathToFileURL(join(repo, 'src/data/photoManifest.ts')).href);

// Same precedence as src/components/common/Img.tsx: photo entries win.
const merged = { ...imageManifest, ...photoManifest };

const phpString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const rows = Object.entries(merged)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([src, e]) => {
    const ladder = e.srcSet.split(',').map((part) => {
      const [url, w] = part.trim().split(/\s+/);
      return [basename(url), parseInt(w, 10)];
    });
    const credit = (photoManifest[src] ?? imageManifest[src])?.credit ?? '';
    return `\t${phpString(basename(src))} => array( 'w' => ${e.width}, 'h' => ${e.height}, 'kind' => ${phpString(
      e.kind
    )}, 'credit' => ${phpString(credit)}, 'ladder' => array( ${ladder
      .map(([f, w]) => `array( ${phpString(f)}, ${w} )`)
      .join(', ')} ) ),`;
  });

writeFileSync(
  out,
  [
    '<?php',
    '/**',
    ' * GENERATED by wordpress/build/build-manifest.mjs from src/data/*Manifest.ts — do not edit.',
    " * file => [ w, h, kind, credit ('artist'|'representative'|''), ladder [ [file, width], … ] ]",
    ' */',
    "defined( 'ABSPATH' ) || exit;",
    '',
    'return array(',
    ...rows,
    ');',
    '',
  ].join('\n')
);
console.log(`media-manifest.php: ${rows.length} images`);
