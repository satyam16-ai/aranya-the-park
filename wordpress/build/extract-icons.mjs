/**
 * extract-icons.mjs — lucide-react → plugin/aranya-core/includes/icons.php
 *
 * The React site draws its icons with lucide-react. To keep the WordPress
 * markup identical, every icon the site (and the Elementor icon pickers) can
 * use is rendered here with react-dom/server — the same code path React uses —
 * and stored as { class, inner }. aranya_icon() in PHP then rebuilds the exact
 * <svg> React would have printed for a given size, stroke width and className.
 *
 * Re-run after upgrading lucide-react or adding an icon: `npm run build:icons`.
 */
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as lucide from 'lucide-react';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const out = join(here, '..', 'plugin', 'aranya-core', 'includes', 'icons.php');

/** Every lucide icon imported anywhere in the React source. */
function iconsUsedInReact() {
  const names = new Set();
  const walk = (dir) => {
    for (const f of readdirSync(dir)) {
      const p = join(dir, f);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(tsx|ts)$/.test(f)) {
        const src = readFileSync(p, 'utf8');
        for (const m of src.matchAll(/import\s*\{([^}]+)\}\s*from\s*'lucide-react'/g)) {
          m[1].split(',').map((s) => s.trim()).filter(Boolean).forEach((n) => names.add(n));
        }
      }
    }
  };
  walk(join(repo, 'src'));
  return names;
}

/** Extra glyphs offered in the Elementor icon pickers, so editors have choices. */
const EXTRA = [
  'Home', 'Building2', 'Trees', 'TreePine', 'Waves', 'Bike', 'Car', 'Coffee', 'BookOpen',
  'Music', 'Utensils', 'ShieldCheck', 'Star', 'Heart', 'Camera', 'Wifi', 'Plane', 'Bus',
  'GraduationCap', 'Hospital', 'Stethoscope', 'School', 'Landmark', 'Mountain', 'Sunrise',
  'Moon', 'Droplets', 'Wind', 'Flame', 'Baby', 'PawPrint', 'Sofa', 'Bath', 'BedDouble',
  'DoorOpen', 'DoorClosed', 'Compass', 'Sparkles', 'Trophy', 'GlassWater', 'Train',
  'ShoppingBag', 'MapPin', 'Navigation', 'Clock', 'Phone', 'Mail', 'MessageSquare', 'Calendar',
  // WordPress-only controls: the plan viewers' rotate and reset-view buttons.
  'RotateCw', 'Scan',
];

const kebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Za-z])([0-9])/g, '$1-$2').toLowerCase();

const names = [...new Set([...iconsUsedInReact(), ...EXTRA])].sort();
const entries = [];
for (const name of names) {
  const Comp = lucide[name];
  if (!Comp) {
    console.warn(`skip: ${name} is not a lucide-react export`);
    continue;
  }
  const html = renderToStaticMarkup(createElement(Comp, { className: '__ARANYA_CLASS__' }));
  const cls = /class="([^"]*)"/.exec(html)[1].replace(' __ARANYA_CLASS__', '').replace('__ARANYA_CLASS__', '').trim();
  const inner = html.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  entries.push({ key: kebab(name), react: name, cls, inner });
}

const php = [
  '<?php',
  '/**',
  ' * GENERATED by wordpress/build/extract-icons.mjs from lucide-react — do not edit.',
  ' * key => [ react component name, base class, inner SVG markup ].',
  ' */',
  "defined( 'ABSPATH' ) || exit;",
  '',
  'return array(',
  ...entries.map(
    (e) =>
      `\t'${e.key}' => array( '${e.react}', '${e.cls}', '${e.inner.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}' ),`
  ),
  ');',
  '',
].join('\n');

writeFileSync(out, php);
console.log(`icons.php: ${entries.length} icons`);
