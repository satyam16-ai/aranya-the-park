/**
 * build-css.mjs — compiles plugin/aranya-core/assets/css/aranya.css
 *
 * The input is generated from the React site's own stylesheet, src/index.css,
 * so the design tokens, component classes, keyframes and the typography
 * hardening block are the same file the React build compiles — a design tweak
 * made there carries over on the next build. Only two things change:
 *
 *  1. `@import "tailwindcss"` scans the WordPress PHP/JS instead of src/, so
 *     every class string the widgets print is generated.
 *  2. build/wp-additions.css is appended: Alpine's x-cloak, and the layer that
 *     keeps Elementor's unlayered frontend CSS from overriding Tailwind.
 *
 * Usage: node build/build-css.mjs [--watch]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync, spawn } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const generated = join(here, '.tailwind.generated.css');
const output = join(here, '..', 'plugin', 'aranya-core', 'assets', 'css', 'aranya.css');

const source = readFileSync(join(repo, 'src', 'index.css'), 'utf8');
const IMPORT = '@import "tailwindcss";';
if (!source.includes(IMPORT)) throw new Error(`src/index.css no longer starts with ${IMPORT}`);

const header = [
  '/* GENERATED by wordpress/build/build-css.mjs from src/index.css — edit those, not this. */',
  '@import "tailwindcss" source(none);',
  '@source "../plugin/aranya-core/includes";',
  '@source "../plugin/aranya-core/templates";',
  '@source "../plugin/aranya-core/assets/src";',
  '@source "../theme/aranya";',
].join('\n');

const css =
  source.replace(IMPORT, header) +
  '\n\n/* ===== WordPress additions (build/wp-additions.css) ===== */\n' +
  readFileSync(join(here, 'wp-additions.css'), 'utf8');
writeFileSync(generated, css);

const bin = join(here, '..', 'node_modules', '.bin', process.platform === 'win32' ? 'tailwindcss.cmd' : 'tailwindcss');
const args = ['-i', generated, '-o', output, ...(process.argv.includes('--watch') ? ['--watch'] : ['--minify'])];

if (process.argv.includes('--watch')) {
  spawn(bin, args, { stdio: 'inherit', shell: true });
} else {
  const r = spawnSync(bin, args, { stdio: 'inherit', shell: true });
  process.exit(r.status ?? 1);
}
